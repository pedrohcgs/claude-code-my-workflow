#!/usr/bin/env python3
"""Generate the `.agents/skills/` bridge, so Codex and Antigravity can use the skills in `.claude/skills/`.

Codex and Google Antigravity read skills in the open Agent Skills format (a folder with a
SKILL.md) from `.agents/skills/` at the repository root. Claude Code reads `.claude/skills/`.
Rather than keep two copies that drift, each bridged skill gets a small generated wrapper:
the same `name` and the same `description` line (so the other agent routes to it for the same
requests), and a body that sends the agent to the real instructions in `.claude/skills/`, with
notes on what does not carry over from Claude Code. Real copies or symlinks are avoided:
copies drift, and the repository supports Windows hosts that cannot create symlinks.

Only skills that one agent can run end to end are bridged. A skill whose whole point is
several independent reviewers (`/review-paper --peer`, `/seven-pass-review`,
`/verify-claims`, ...), or one that manages Claude Code itself (`/checkpoint`, `/learn`, ...),
is listed in EXCLUDE with the reason. `scripts/check-skill-integrity.py` (check 6) fails on a
missing or stale wrapper, a wrapper with no source, or a skill in both lists, and warns (without
failing) about a skill in neither list — a fork's own new skill stays Claude-only until someone
decides to bridge it.

Skills Claude Code marks `disable-model-invocation: true`, plus /commit, also get an
`agents/openai.yaml` that tells Codex not to start them on its own (`allow_implicit_invocation:
false`); they still run when asked for by name.

Usage:
  python3 scripts/sync-agent-skills.py           # write or refresh the wrappers
  python3 scripts/sync-agent-skills.py --check   # change nothing; exit 1 if anything is out of date
                                                 # (--dry-run is the same)
"""
from __future__ import annotations

import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent      # resolved before anything else
SRC = REPO / ".claude" / "skills"
DST = REPO / ".agents" / "skills"

INCLUDE = [
    # research and writing
    "interview-me", "lit-review", "research-ideation", "preregister", "grant-proposal",
    "data-management-plan", "credible-claims", "submission-disclosures", "respond-to-referees",
    "respond-to-eval", "coauthor-brief", "adjudicate-review", "humanize",
    # data, code and reproducibility
    "data-analysis", "stata-replication", "simulation-study", "power-analysis",
    "audit-reproducibility", "replication-package", "capture-environment", "disclosure-check",
    "diagnose", "differential-audit", "blast-radius", "verify-artifact", "r-package-check",
    "review-r",
    # slides and teaching
    "create-lecture", "compile-latex", "deploy", "extract-tikz", "new-diagram", "syllabus",
    "teach-from-paper", "scaffold-exercises", "proofread", "visual-audit", "pedagogy-review",
    "devils-advocate", "validate-bib",
    # shipping and tracking
    "commit", "issues",
]
EXCLUDE = {
    # The value is independent or parallel reviewers, which one agent cannot honestly supply.
    "review-paper": "editor plus two independent referees",
    "seven-pass-review": "seven parallel fresh-context reviewers",
    "verify-claims": "a fresh-context verifier that never sees the draft",
    "challenge": "fan-out over alternative analysis paths",
    "vaccinate": "a checker run blind against seeded defects",
    "slide-excellence": "a fan-out of reviewer agents in a forked context",
    "qa-quarto": "a critic and a fixer agent looping in a forked context",
    "translate-to-quarto": "runs in a forked context with the translator agent",
    "voice-profile": "reads the corpus one document per subagent",
    # About Claude Code itself: its sessions, memory, permissions, or skill authoring.
    "checkpoint": "Claude Code session handoff",
    "compress-session": "Claude Code context compaction",
    "context-status": "Claude Code context status",
    "permission-check": "Claude Code permission settings",
    "learn": "Claude Code auto memory",
    "promote-memory": "Claude Code auto memory, with a council of agents",
    "new-skill": "authors skills for .claude/skills",
    "deep-audit": "audits this template's Claude Code infrastructure",
    "oracle-review": "Claude Code driving another vendor's model",
    "triage-inbox": "claude.ai Gmail and Calendar connectors",
}
NO_IMPLICIT = {"commit"}          # in addition to disable-model-invocation: true

HEADER = ("<!-- Generated by scripts/sync-agent-skills.py from .claude/skills/{name}/SKILL.md. "
          "Do not edit: change the source and re-run the script. -->")
BODY = """
# {name}

This skill's instructions live in [`.claude/skills/{name}/SKILL.md`](../../../.claude/skills/{name}/SKILL.md).
Read that file now and follow it, with the files it points to. Read [`AGENTS.md`](../../../AGENTS.md)
first if you have not already.

It was written for Claude Code. Running it from Codex, Antigravity or another agent:

- **Arguments.** Where it says `$ARGUMENTS`, use what the user asked for.
- **Claude Code agents.** Where a step hands work to an agent in `.claude/agents/` (through the
  `Agent` or `Task` tool), do that step where it appears in the procedure: never later, and never
  skip it. A step that gates what follows still gates it (`/commit` runs its verifier before it
  commits). Read the agent's file for what the step checks.
- **Fresh context.** If the step needs a context that has not seen your work, for example a claim
  verifier that must never see the draft, run it in a separate session or worker that has not
  seen the draft, if your tool can start one, and give it only what the step says to pass. If it
  cannot, do the step yourself, mark every result it produced *not independently verified*, and
  tell the user to repeat that check in Claude Code (`/verify-claims` for citations) before
  relying on it.
- **Claude Code settings.** `allowed-tools`, `model`, `effort`, `argument-hint` and
  `disable-model-invocation` in the source's frontmatter configure Claude Code. Ignore them.
- **Guards.** Claude Code's guard hooks do not run for you. Follow the rules in `AGENTS.md`
  yourself; the git pre-commit gate and CI still apply to your commits.
"""
OPENAI_YAML = """# Generated by scripts/sync-agent-skills.py. Codex runs this skill only when asked for it.
policy:
  allow_implicit_invocation: false
"""


def _frontmatter(text: str) -> str:
    if not text.startswith("---"):
        raise ValueError("no frontmatter")
    return text.split("---", 2)[1]


def expected() -> dict[pathlib.Path, str]:
    """Every file the bridge should contain, keyed by absolute path."""
    out: dict[pathlib.Path, str] = {}
    for name in INCLUDE:
        src = SRC / name / "SKILL.md"
        fm = _frontmatter(src.read_text(encoding="utf-8"))
        desc = next(l for l in fm.splitlines() if l.startswith("description:"))
        text = (f"---\nname: {name}\n{desc}\n---\n" + HEADER.format(name=name) + "\n"
                + BODY.format(name=name))
        out[DST / name / "SKILL.md"] = text
        if name in NO_IMPLICIT or re.search(r"^disable-model-invocation:\s*true\s*$", fm, re.M):
            out[DST / name / "agents" / "openai.yaml"] = OPENAI_YAML
    return out


def unclassified() -> list[str]:
    """Skills in neither list: Claude-only until someone bridges or excludes them (a warning)."""
    skills = {p.parent.name for p in SRC.glob("*/SKILL.md")}
    return [f".claude/skills/{n}: not classified — it stays Claude-only; to bridge it for Codex and "
            "Antigravity, add it to INCLUDE in scripts/sync-agent-skills.py and run the script "
            "(or add it to EXCLUDE with the reason)"
            for n in sorted(skills - set(INCLUDE) - set(EXCLUDE))]


def problems() -> list[str]:
    """What is wrong with the bridge on disk (each one fails the check); empty when current."""
    errs: list[str] = []
    skills = {p.parent.name for p in SRC.glob("*/SKILL.md")}
    for n in sorted(set(INCLUDE) & set(EXCLUDE)):
        errs.append(f"{n}: listed in both INCLUDE and EXCLUDE")
    for n in sorted((set(INCLUDE) | set(EXCLUDE)) - skills):
        errs.append(f"{n}: listed in scripts/sync-agent-skills.py but .claude/skills/{n}/SKILL.md does not exist")
    if errs:
        return errs
    want = expected()
    for path, text in sorted(want.items()):
        rel = path.relative_to(REPO).as_posix()
        if not path.exists():
            errs.append(f"{rel}: missing — run python3 scripts/sync-agent-skills.py")
        elif path.read_text(encoding="utf-8") != text:
            errs.append(f"{rel}: out of date with its source — run python3 scripts/sync-agent-skills.py")
    if DST.exists():
        for path in sorted(p for p in DST.rglob("*") if p.is_file()):
            if path not in want:
                errs.append(f"{path.relative_to(REPO).as_posix()}: not generated from any bridged skill — "
                            "remove it, or bridge its skill in INCLUDE")
    return errs


def main() -> int:
    check = "--check" in sys.argv or "--dry-run" in sys.argv
    if check:
        errs = problems()
        for e in errs:
            print(f"sync-agent-skills: {e}")
        for w in unclassified():
            print(f"sync-agent-skills: warning: {w}")
        if not errs:
            print(f"sync-agent-skills: .agents/skills is current ({len(INCLUDE)} skills bridged, "
                  f"{len(EXCLUDE)} excluded)")
        return 1 if errs else 0
    errs = [e for e in problems() if "listed in" in e]
    for w in unclassified():
        print(f"sync-agent-skills: warning: {w}", file=sys.stderr)
    if errs:
        for e in errs:
            print(f"sync-agent-skills: {e}", file=sys.stderr)
        return 1
    want = expected()
    if DST.exists():
        for path in sorted(p for p in DST.rglob("*") if p.is_file()):
            if path not in want:
                path.unlink()
    for path, text in want.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print(f"sync-agent-skills: wrote {len(want)} files for {len(INCLUDE)} skills into .agents/skills")
    return 0


if __name__ == "__main__":
    sys.exit(main())
